    def evaluate_polygon(self):
        file_pathGt = self.lineEdit_gt.text()
        file_pathPred = self.lineEdit_pred.text()

        if not os.path.exists(file_pathGt) or not os.path.exists(file_pathPred):
            print("파일 경로가 올바르지 않습니다.")
            return
        
        # 0. Shape 파일 읽어서 벡터 레이어 객체 생성
        gt_layer = QgsVectorLayer(file_pathGt, "gt", "ogr")
        pred_layer = QgsVectorLayer(file_pathPred, "pred", "ogr")

        if not gt_layer.isValid() or not pred_layer.isValid():
            print("레이어 로드 실패")
            return

        # 1. 좌표계 동일한지 확인
        if gt_layer.crs() != pred_layer.crs():
            print(f"GT crs: {gt_layer.crs()}, Pred crs: {pred_layer.crs()}" )
            print("좌표계가 다릅니다.")
            return

        # 2. IoU Threshold 값 가져오기
        iou_threshold = self.doubleSpinBox.value()
        print(f"IoU Threshold: {iou_threshold}")

        # 3. Feature 리스트 만들기
        gt_features = list(gt_layer.getFeatures())
        pred_features = list(pred_layer.getFeatures())

        # 4. matching 관리
        # 하나의 GT Polygon이 여러 Pred와 중복 TP되면 안 됨
        # 따라서 중복 불가능한 set 사용
        matched_gt = set()
        matched_pred = set() # GT와 성공적으로 매칭된 Pred polygon들

        # 5. polygon matching
        # 각 GT polygon마다 가장 많이 겹치는 Pred polygon 찾기
        tp = 0
        result_rows = []

        # 각 GT polygon마다 가장 IoU가 높은 Pred polygon 하나를 찾고, Threshold 이상이면서 type이 같으면 TP로 인정
        for gt_idx, gt_feat in enumerate(gt_features): # GT 하나씩 꺼내기
            gt_geom = gt_feat.geometry()

            best_iou = 0 # 가장 높은 IoU 저장
            best_pred_idx = -1
            
            # 모든 Pred와 비교 
            for pred_idx, pred_feat in enumerate(pred_features):
                # 이미 사용된 Pred는 건너뜀
                if pred_idx in matched_pred:
                    continue
                
                pred_geom = pred_feat.geometry()

                # type 가져오기
                gt_type = str(gt_feat["Shape_Type"]).lower()
                pred_type = str(pred_feat["type"]).lower()

                # type 다르면 skip
                if gt_type != pred_type:
                    continue

                # IoU 계산
                iou = self.calculate_iou(gt_geom, pred_geom)

                if iou > best_iou:
                    best_iou = iou
                    best_pred_idx = pred_idx
            
            if best_iou >= iou_threshold:
                tp += 1

                matched_gt.add(gt_idx)
                matched_pred.add(best_pred_idx)

                gt_points = self.extract_polygon_points(gt_geom) # 폴리곤 좌표 추출

                pred_geom = pred_features[best_pred_idx].geometry()
                pred_points = self.extract_polygon_points(pred_geom)

                # if len(gt_points) != len(pred_points):
                #     continue

                # 좌표 오차 계산
                errors = self.calculate_coordinate_errors(
                    gt_points,
                    pred_points
                )

                # 면적 계산
                gt_area = gt_geom.area()
                pred_area = pred_geom.area()

                # symDifference: 겹치지 않는 부분만 남김
                error_geom = gt_geom.symDifference(pred_geom) 
                error_area = error_geom.area()

                # csv 저장용 데이터
                result_rows.append({
                    "gt_points": gt_points,
                    "gt_area": gt_area,

                    "pred_points": pred_points,
                    "pred_area": pred_area,

                    "errors": errors,
                    "error_area": error_area
                })

        # FP / FN 계산 
        fp = len(pred_features) - len(matched_pred) # 전체 Pred 개수 - 매칭 성공한 Pred 개수
        fn = len(gt_features) - len(matched_gt) # 전체 GT 개수 - 매칭 성공한 GT 개수 = 미탐

        # Precision / Recall / F1 Score 계산
        precision = tp / (tp + fp) if (tp + fp) > 0 else 0
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0
        f1_score = (
            2 * precision * recall / (precision + recall)
            if (precision + recall) > 0 else 0
        )

        # 결과 출력
        print(f"TP: {tp}")
        print(f"FP: {fp}")
        print(f"FN: {fn}")

        print(f"Precision: {precision:.4f}")
        print(f"Recall: {recall:.4f}")
        print(f"F1 Score: {f1_score:.4f}")

        self.label_precision.setText(f"Precision: {precision:.4f}")
        self.label_recall.setText(f"Recall: {recall:.4f}")
        self.label_f1Score.setText(f"F1 Score: {f1_score:.4f}")

        # 결과를 csv 파일로 저장
        self.create_csv(tp, fp, fn, precision, recall, f1_score, result_rows)

    # IoU 계산 함수
    def calculate_iou(self, geom1, geom2):
        # 실제 겹치는 부분 계산
        # 여기서 intersection은 겹치는 polygon geometry(객체)
        intersection = geom1.intersection(geom2)

        if intersection.isEmpty():
            return 0.0

        # 겹치는 polygon의 실제 면적 계산 
        intersection_area = intersection.area()

        # GT polygon과 Pred polygon의 각 면적 계산
        area1 = geom1.area()
        area2 = geom2.area()

        # 두 polygon의 겹치는 부분 빼줌
        union_area = area1 + area2 - intersection_area

        if union_area == 0:
            return 0.0

        iou = intersection_area / union_area

        return iou

