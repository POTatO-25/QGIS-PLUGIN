    # polygon 좌표 추출 함수
    # QGIS polygon 구조는 아래와 같음
    # Polygon
    #   ㄴ Ring(외곽선)
    #       ㄴ Points(0,0)
    #       ㄴ Points(10,0)
    #       ㄴ Points(10,10)
    #       ㄴ Points(0,10)
    #       ㄴ Points(0,0) <-- 시작점 반복
    def extract_polygon_points(self, geom):
        points = []

        # 일반 polygon
        if geom.isMultipart() == False:
            polygon = geom.asPolygon()

            if not polygon:
                return []

            # polygon[0]은 첫 번째 ring을 꺼내는 것임
            # [
            #    [ Point(0,0),
            #      Point(10,0),
            #      Point(10,10),
            #      Point(0,10),
            #      Point(0,0)
            #    ]
            # ]
            ring = polygon[0]

            for pt in ring[:-1]: # 마지막 점이 시작점 반복하기 때문에 마지막 점 제외하기 위해서 -1
                points.append((pt.x(), pt.y()))
        else:
            # MultiPolygon 구조
            # QGIS polygon 구조는 아래와 같음
            # MultiPolygon
            # ㄴ Polygon
            #    ㄴ Ring(외곽선)
            #       ㄴ Points
            # [
            #    [
            #       [ Point(0,0),
            #         Point(10,0),
            #         Point(10,10),
            #         Point(0,10),
            #         Point(0,0)
            #       ]
            #    ]
            # ]
            multipolygon = geom.asMultiPolygon()

            if not multipolygon:
                return []

            # 첫 번째 polygon만 사용
            ring = multipolygon[0][0]

            for pt in ring[:-1]:
                points.append((pt.x(), pt.y()))
        
        return points

